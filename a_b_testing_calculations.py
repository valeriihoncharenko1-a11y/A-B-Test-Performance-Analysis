segment_cols = ['continent', 'country', 'device', 'channel']
results_list = []

def process_segment_group(df, group_keys, seg_type):
    # Calculate total sessions for each segment slice and test group
    sessions_seg = (
        df[df['event_name'] == 'session']
        .groupby(group_keys)['total_value']
        .sum()
        .reset_index(name='total_sessions')
    )

    # Calculate total events for each segment slice and test group
    events_seg = (
        df.groupby(group_keys + ['event_name'])['total_value']
        .sum()
        .reset_index(name='event_count')
    )

    # Merge events with total sessions
    merged_seg = pd.merge(events_seg, sessions_seg, on=group_keys)

    # Identify control and test groups
    groups = sorted(merged_seg['test_group'].unique())

    if len(groups) >= 2:
        ctrl_group = groups[0]
        test_group = groups[1]

        # Filter and prepare control group dataframe
        df_ctrl = merged_seg[merged_seg['test_group'] == ctrl_group].drop(
            columns=['test_group']
        )
        df_ctrl = df_ctrl.rename(
            columns={
                'event_count': 'ctrl_events',
                'total_sessions': 'ctrl_sessions',
            }
        )

        # Filter and prepare test group dataframe
        df_tst = merged_seg[merged_seg['test_group'] == test_group].drop(
            columns=['test_group']
        )
        df_tst = df_tst.rename(
            columns={
                'event_count': 'test_events',
                'total_sessions': 'test_sessions',
            }
        )

        # Merge control and test dataframes
        merge_keys = ['test', 'event_name'] + [col for col in group_keys if col not in ['test', 'test_group']]
        segments_comparison = pd.merge(df_ctrl, df_tst, on=merge_keys, how='inner')

        # Function to calculate Z-test p-value for each segment row
        def calculate_segment_ztest(row):
            successes = [int(row['ctrl_events']), int(row['test_events'])]
            nobs = [int(row['ctrl_sessions']), int(row['test_sessions'])]

            if (
                nobs[0] > 0
                and nobs[1] > 0
                and successes[0] <= nobs[0]
                and successes[1] <= nobs[1]
            ):
                try:
                    _, p_val = proportions_ztest(successes, nobs)
                    return p_val
                except:
                    return float('nan')
            return float('nan')

        # Apply Z-test function across the dataframe
        segments_comparison['p_value'] = segments_comparison.apply(
            calculate_segment_ztest, axis=1
        )

        # Calculate conversion rates (CR) for control and test
        segments_comparison['control_cr'] = (
            segments_comparison['ctrl_events'] / segments_comparison['ctrl_sessions']
        )
        segments_comparison['test_cr'] = (
            segments_comparison['test_events'] / segments_comparison['test_sessions']
        )

        # Calculate absolute difference in percentage points
        segments_comparison['cr_diff_abs_pct'] = (
            (segments_comparison['test_cr'] - segments_comparison['control_cr']) * 100
        )

        # Calculate relative difference percentage
        segments_comparison['cr_rel_pct'] = (
            (segments_comparison['test_cr'] - segments_comparison['control_cr'])
            / segments_comparison['control_cr']
            * 100
        )

        # Determine statistical significance flag
        segments_comparison['is_significant'] = segments_comparison['p_value'].apply(
            lambda x: True if pd.notna(x) and x < 0.05 else False
        )

        # Adding columns segment_type and segment_val
        segments_comparison['segment_type'] = seg_type
        segments_comparison['segment_val'] = segments_comparison[seg_type]
        segments_comparison = segments_comparison.drop(columns=[seg_type])

        return segments_comparison
    return None

for col in segment_cols:
    res_dim = process_segment_group(df, ['test', 'test_group', col], col)
    if res_dim is not None:
        results_list.append(res_dim)

segments_comparison = pd.concat(results_list, ignore_index=True)

cols_order = ['test', 'segment_type', 'segment_val', 'event_name',
              'ctrl_events', 'ctrl_sessions', 'test_events', 'test_sessions',
              'control_cr', 'test_cr', 'p_value', 'is_significant',
              'cr_diff_abs_pct', 'cr_rel_pct']
existing_cols = [c for c in cols_order if c in segments_comparison.columns]
other_cols = [c for c in segments_comparison.columns if c not in existing_cols]
segments_comparison = segments_comparison[existing_cols + other_cols]

