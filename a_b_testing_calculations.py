#Calculate the total number of sessions for each group in each test
sessions_df = (
    df[df['event_name'] == 'session']
    .groupby(['test', 'test_group'])['total_value']
    .sum()
    .reset_index(name='total_sessions')
)

#Calculate the sum of all events for each group in each test
events_df = (
    df.groupby(['test', 'test_group', 'event_name'])['total_value']
    .sum()
    .reset_index(name='event_count')
)

# Grouping events with total number of sessions
merged_df = pd.merge(events_df, sessions_df, on=['test', 'test_group'])


#Running a loop to calculate the Z-test for the total
results = []

tests = merged_df['test'].unique()
events = merged_df['event_name'].unique()

#Identifying which groups are control groups and which are test groups
groups = sorted(merged_df['test_group'].unique())

if len(groups) >= 2:
  control_group = groups[
      0
  ]
  test_group = groups[1]

  for test_id in tests:
    for ev in events:
      #Skipping `session` because it is a denominator
      if ev == 'session':
        continue

      #Extracting data for the control group
      ctrl_row = merged_df[
          (merged_df['test'] == test_id)
          & (merged_df['test_group'] == control_group)
          & (merged_df['event_name'] == ev)
      ]

      # Extracting data for the test group
      tst_row = merged_df[
          (merged_df['test'] == test_id)
          & (merged_df['test_group'] == test_group)
          & (merged_df['event_name'] == ev)
      ]

      if not ctrl_row.empty and not tst_row.empty:
        successes = [
            int(ctrl_row['event_count'].values[0]),
            int(tst_row['event_count'].values[0]),
        ]
        nobs = [
            int(ctrl_row['total_sessions'].values[0]),
            int(tst_row['total_sessions'].values[0]),
        ]

        if nobs[0] > 0 and nobs[1] > 0:
          z_stat, p_val = proportions_ztest(successes, nobs)

          ctrl_cr = successes[0] / nobs[0]
          test_cr = successes[1] / nobs[1]

          #Calculating cr difference
          cr_diff_abs = test_cr - ctrl_cr
          cr_diff_relative = (
              (test_cr - ctrl_cr) / ctrl_cr if ctrl_cr > 0 else 0
          )

          #Checking statistical significance
          is_sig = (
              True if pd.notna(p_val) and p_val < 0.05 else False
          )

          results.append({
              'test': test_id,
              'event_name': ev,
              'control_sessions': nobs[0],
              'test_sessions': nobs[1],
              'control_events': successes[0],
              'test_events': successes[1],
              'control_cr': ctrl_cr,
              'test_cr': test_cr,
              'cr_difference_abs': cr_diff_abs,
              'cr_difference_rel': cr_diff_relative
              * 100,
              'p_value': p_val,
              'is_significant': is_sig,
          })
#Creating dataframe with results
total_results_df = pd.DataFrame(results)

total_results_df.to_csv("total.csv", index=False, encoding="utf-8-sig")

